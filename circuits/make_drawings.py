# ---------------------------------------------------------------- rectifier (single-phase drawing of a three-phase supply)
d = Drawing(settings={"dt": "20u", "tstop": "120m"})
rows = {"a": 6, "b": 12, "c": 18}
angles = {"a": "0", "b": "-120", "c": "120"}
X0 = 12                              # bridges start right of the source labels
for p, y in rows.items():           # phase sources, each behind R + L, feeding a bus wire at y - 2
    d.add("V", "SUPPLY." + p, 2, y + 2, 270, mag="326.6", angle=angles[p], freq="50", r="0.005", l="0.1m")
    d.gnd(2, y + 2)
    d.wire((2, y - 2), (X0 + 28, y - 2))
# valves: lower valve DC- -> phase node, upper valve phase node -> DC+ (natural commutation refs)
thy = {"a": ("T1", "60", "T4", "-120"), "b": ("T3", "-60", "T6", "120"), "c": ("T5", "-180", "T2", "0")}
dio = {"a": ("D1", "D4"), "b": ("D3", "D6"), "c": ("D5", "D2")}
for p, y in rows.items():
    up, ref_up, lo, ref_lo = thy[p]
    T, Dd = X0 + 4, X0 + 24                           # phase nodes of the two bridges
    d.wire((T, y - 2), (T, y))                        # thyristor bridge: phase node (T, y)
    d.add("THY", lo, T - 4, y, 0, alpha="30", freq="50", ref=ref_lo, width="120", ron="1m", roff="1meg")
    d.add("THY", up, T, y, 0, alpha="30", freq="50", ref=ref_up, width="120", ron="1m", roff="1meg")
    d.wire((T + 4, y), (T + 6, y))
    du, dl = dio[p]
    d.wire((Dd, y - 2), (Dd, y))                      # diode bridge: phase node (Dd, y)
    d.add("D", dl, Dd - 4, y, 0, ron="1m", roff="1meg", vf="")
    d.add("D", du, Dd, y, 0, ron="1m", roff="1meg", vf="")
    d.wire((Dd + 4, y), (Dd + 6, y))
T, Dd = X0 + 4, X0 + 24
d.wire((T - 4, 6), (T - 4, 18)); d.wire((T + 6, 6), (T + 6, 18))      # thyristor bridge DC- and DC+ rails
d.wire((Dd - 4, 6), (Dd - 4, 18)); d.wire((Dd + 6, 6), (Dd + 6, 18))  # diode bridge DC- and DC+ rails
# thyristor bridge DC side: smoothing reactor and load back to DC-
d.wire((T + 6, 18), (T + 6, 22), (T + 7, 22))
d.add("L", "LDC", T + 7, 22, 0, value="5m")
d.add("R", "RLOAD", T + 11, 22, 90, value="5")
d.wire((T + 11, 26), (T - 4, 26), (T - 4, 18))
d.shunt_down("R", "REF_T", T - 1, 26, value="1e6")
# diode bridge DC side: capacitor and load
d.wire((Dd + 6, 18), (Dd + 6, 22), (Dd + 10, 22))
d.add("C", "CDC", Dd + 6, 22, 90, value="2000u")
d.add("R", "RDC", Dd + 10, 22, 90, value="10")
d.wire((Dd + 10, 26), (Dd - 4, 26), (Dd - 4, 18))
d.shunt_down("R", "REF_D", Dd - 1, 26, value="1e6")
save("rectifier", d, "six-pulse rectifiers", """
Six-pulse thyristor rectifier (firing angle 30 deg) and diode rectifier on a 400 V supply

  SUPPLY (400 V, three phase sources each behind R + L -> commutation overlap)
    -- thyristor bridge T1..T6 -- DC: smoothing L + 5 ohm load
    -- diode bridge D1..D6     -- DC: 2000 uF capacitor + 10 ohm load

Drawn in single-phase mode (diodes and thyristors are single-phase parts): the three phase
sources SUPPLY.a/b/c are 120 deg apart, each behind 5 mohm + 0.1 mH.
Gate timing: valve k fires alpha degrees after its natural commutation point. With phase a
voltage = Vm cos(wt), the natural points are -60 (T1, a+), 0 (T2, c-), 60 (T3, b+), 120 (T4, a-),
180 (T5, c+) and 240 deg (T6, b-), so each valve gets ref = -(natural point).
Ideal DC voltage of the thyristor bridge: 1.35 x 400 x cos 30 = 468 V, minus the commutation
drop (3/pi) w Ls Id.

Elements used: V behind R + L, THY, D, R, L, C.
""")

