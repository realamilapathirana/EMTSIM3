"""Generate the drawn example studies (fault_clearing, line_energisation, transformer_inrush,
rectifier, machines) so that they open in the circuit editor with a schematic.

    python circuits/make_drawings.py        (needs Node.js for gui/layout_to_net.js)

Each circuit is placed on the editor's grid and its netlist is produced from the drawing by
the editor's own code (gui/schematic.js), as for grid100.net. Element names match the
original hand-written netlists, so the branch currents can be compared by name.
"""
import os

from make_grid100 import Drawing, netlist_from_drawing, write_netlist

HERE = os.path.dirname(os.path.abspath(__file__))


def save(name, d, title, description, allow_warnings=False):
    text, nodes, counts = netlist_from_drawing(d, title, allow_warnings)
    write_netlist(os.path.join(HERE, name + ".net"), text,
                  ["# " + l if l else "#" for l in description.strip("\n").splitlines()] +
                  ["#", "# Generated by circuits/make_drawings.py; open it in the circuit editor (gui.bat) to see the drawing."])
    print("Wrote circuits/%s.net: %d nodes, %s" % (name, nodes, counts))


